const event = { id: 1, tema: 'Oficina de Desenvolvimento Web', descricao: 'Evento fictício para revisão do Muttley.', data: '2026-09-01', horarioInicio: '14:00', horarioFim: '16:00', modalidade: 'PRESENCIAL', status: 'EM_ANDAMENTO', disciplina: { id: 1, nome: 'Engenharia de Software' }, local: { id: 1, nome: 'Auditório', capacidade: 80 }, patrocinador: { id: 1, nome: 'Instituição' } };
