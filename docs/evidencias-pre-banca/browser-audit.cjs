    await page.getByText(event.tema, { exact: true }).waitFor();
    await page.screenshot({ path: path.join(__dirname, 'public-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(__dirname, 'public-mobile.png'), fullPage: true });
    result.checks.push({ name: 'Lista pública mobile 390px', horizontalOverflow: await page.evaluate(() => document.documentElement.scrollWidth > innerWidth) });
    authenticated = true;
    await page.evaluate(() => localStorage.setItem('usuario', JSON.stringify({ id: 1, nome: 'Admin Demonstração', role: 'ADMIN' })));
    await page.setViewportSize({ width: 1366, height: 900 });
